// Ujian akhir per level: soal berbasis kasus yang menggabungkan beberapa materi.
// `topik` = id materi untuk tautan "pelajari lagi" saat jawaban salah. Lulus jika skor ≥ BATAS_LULUS.

export const BATAS_LULUS = 0.75

const u = (topik, q, options, answer, why) => ({ topik, q, ...acakTetap(q, options, answer), why })

// Agar menebak satu huruf terus tidak menguntungkan, posisi jawaban benar diratakan:
// dalam setiap 4 soal berurutan, jawaban benar ada tepat sekali di A, B, C, dan D.
const POLA = [2, 0, 3, 1]
function ratakan(daftar) {
  return daftar.map((s, k) => {
    const target = POLA[k % 4] % s.options.length
    const lain = s.options.filter((_, j) => j !== s.answer)
    lain.splice(target, 0, s.options[s.answer])
    return { ...s, options: lain, answer: target }
  })
}

